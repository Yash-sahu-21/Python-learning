## Data Types

# Integer (whole number) (int)(negative or positive)
age = 19
print(type(age))

# string (text)('' or ""or ''' ''')
name = "Yash"
print(type(name))

# float (decimal number)    
pi = 3.14
print(type(pi)) 

# boolean (true or false)
is_adult = True
print(type(is_adult))

# none type (no value)
value = None                    
print(type(value))