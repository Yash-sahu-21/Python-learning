# Type Conversion in Python

# String to Integer
a = "2026"
b = int(a)
print(b, type(b))

# Integer to Float
x = 108
y = float(x)
print(y, type(y))

# Integer to String
num = 1881
text = str(num)
print(text, type(text))

# Integer to Boolean
value = 0
result = bool(value)
print(result, type(result))