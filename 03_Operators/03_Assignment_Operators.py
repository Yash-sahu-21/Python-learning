# ASSIGNMENT OPERATORS 

a = 10
print("Initial value of a:", a)

a = 15
print("Value of a after assignment:", a)

a += 10
print("Value of a after addition assignment (a += 10):", a)

a -= 5
print("Value of a after subtraction assignment (a -= 5):", a)

a *= 2
print("Value of a after multiplication assignment (a *= 2):", a)

a /= 5
print("Value of a after division assignment (a /= 5):", a)

a %= 10
print("Value of a after modulo assignment (a %= 10):", a)

a //= 2
print("Value of a after floor division assignment (a //= 2):", a)

a **= 2
print("Value of a after power assignment (a **= 2):", a)
