# COMPARISON OPERATORS (returns a boolean value True or False)

a = 2
b = 4

print("a =", a, "b =", b)

# EQUAL TO
equal_to = a == b
print("Equal To:", equal_to)

# NOT EQUAL TO
not_equal_to = a != b
print("Not Equal To:", not_equal_to)

# GREATER THAN
greater_than = b > a
print("Greater Than:", greater_than)

# LESS THAN
less_than = b < a
print("Less Than:", less_than)

# GREATER THAN OR EQUAL TO
greater_than_or_equal_to = b >= a
print("Greater Than Or Equal To:", greater_than_or_equal_to)

# LESS THAN OR EQUAL TO
less_than_or_equal_to = b <= a
print("Less Than Or Equal To:", less_than_or_equal_to)