# logical operators

# AND operator(TRUE if both operands are TRUE)
x = True
y = False
z = x and y
print("x and y:", z)

# OR operator(TRUE if at least one operand is TRUE)
x = True
y = False
z = x or y
print("x or y:", z)

# NOT operator(TRUE if operand is FALSE)
x = True
z = not x
print("not x:", z)